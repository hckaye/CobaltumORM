    [Fact]
    public void PreservesEscapeStringDefaultsContainingAnEscapedQuote()
    {
        const string sql = """CREATE TABLE events (message text DEFAULT E'escaped\'; value' NOT NULL);""";

        var result = PostgreSqlMigrationAnalyzer.Analyze(
            new DatabaseSchema(Array.Empty<Table>()),
            sql);

        Assert.False(result.HasErrors, string.Join("\n", result.Diagnostics.Select(item => item.ToString())));
        Assert.Equal("E'escaped\\'; value'", Assert.Single(result.Schema.Tables).Columns[0].DefaultExpression);
    }

    [Fact]
    public void AcceptsCommonConstraintsGeneratedColumnsAndDefaultChanges()
    {
        const string sql = @"
            CREATE TABLE groups (
                id integer PRIMARY KEY,
                code text UNIQUE
            );
            CREATE TABLE members (
                id integer PRIMARY KEY,
                group_id integer REFERENCES groups(id) ON DELETE CASCADE,
                score integer CHECK (score >= 0),
                label text GENERATED ALWAYS AS (group_id::text) STORED,
                CONSTRAINT members_group_fk FOREIGN KEY (group_id) REFERENCES groups(id),
                CONSTRAINT members_score_uq UNIQUE (score)
            );
            ALTER TABLE members ADD CONSTRAINT members_score_check CHECK (score < 1000);
            ALTER TABLE members ALTER COLUMN score SET DEFAULT 0;
            ALTER TABLE members ALTER COLUMN score DROP DEFAULT;
            ALTER TABLE members DROP CONSTRAINT members_score_check;";

        var result = PostgreSqlMigrationAnalyzer.Analyze(
            new DatabaseSchema(Array.Empty<Table>()),
            sql);

        Assert.False(result.HasErrors, string.Join("\n", result.Diagnostics.Select(item => item.ToString())));
        var members = Assert.Single(result.Schema.Tables, item => item.Name == "members");
        Assert.Equal(4, members.Columns.Count);
        Assert.Null(members.Columns.Single(item => item.Name == "score").DefaultExpression);
    }
