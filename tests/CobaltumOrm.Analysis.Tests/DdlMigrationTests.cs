    [Fact]
    public void CreatesQuotedAndUnquotedTablesAcrossCommentedStatements()
    {
        const string sql = @"
            -- Flyway comments may sit between statements.
            CREATE TABLE ""Users"" (
                ""Id"" serial PRIMARY KEY,
                ""display name"" VARCHAR(80) NULL,
                amount NUMERIC(12, 2) DEFAULT mystery_function(1.2, 1) NOT NULL,
                created_at TIMESTAMP(3) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
            );
            /* A block comment, including a nested /* comment */, is ignored. */
            CREATE TABLE IF NOT EXISTS audit_log (
                id BIGSERIAL NOT NULL,
                message text DEFAULT 'contains ; and -- text'
            );";

        var result = PostgreSqlMigrationAnalyzer.Analyze(new DatabaseSchema(Array.Empty<Table>()), sql);

        Assert.False(result.HasErrors, string.Join("\n", result.Diagnostics.Select(item => item.ToString())));
        var users = Assert.Single(result.Schema.Tables, item => item.Name == "Users");
        Assert.Equal(4, users.Columns.Count);
        Assert.Equal("Id", users.Columns[0].Name);
        Assert.Equal("serial", users.Columns[0].SqlType);
        Assert.False(users.Columns[0].IsNullable);
        Assert.True(users.Columns[0].IsPrimaryKey);
        Assert.Equal("varchar(80)", users.Columns[1].SqlType);
        Assert.True(users.Columns[1].IsNullable);
        Assert.Equal("numeric(12,2)", users.Columns[2].SqlType);
        Assert.False(users.Columns[2].IsNullable);
        Assert.Equal("mystery_function(1.2, 1)", users.Columns[2].DefaultExpression);
        Assert.Equal("timestamp(3) with time zone", users.Columns[3].SqlType);
        Assert.NotNull(Assert.Single(result.Schema.Tables, item => item.Name == "audit_log"));
    }

