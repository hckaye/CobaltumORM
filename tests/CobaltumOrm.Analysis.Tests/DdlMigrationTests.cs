    [Fact]
    public void AppliesTableEvolutionWithoutChangingTheInputSchema()
    {
        var initial = new DatabaseSchema(new[]
        {
            new Table("accounts", new[]
            {
                new Column("id", "integer"),
                new Column("name", "text"),
            }),
        });

        var result = PostgreSqlMigrationAnalyzer.Analyze(initial, @"
            ALTER TABLE accounts ADD COLUMN created_at timestamptz DEFAULT now() NOT NULL;
            ALTER TABLE accounts ALTER COLUMN name SET NOT NULL;
            ALTER TABLE accounts ALTER COLUMN created_at TYPE timestamp;
            ALTER TABLE accounts RENAME COLUMN name TO display_name;
            ALTER TABLE accounts RENAME TO users;
            ALTER TABLE users ALTER COLUMN display_name DROP NOT NULL;
            ALTER TABLE users ALTER COLUMN display_name SET NOT NULL;
            ALTER TABLE users DROP COLUMN id;");

        Assert.False(result.HasErrors, string.Join("\n", result.Diagnostics.Select(item => item.ToString())));
        Assert.Equal("accounts", initial.Tables[0].Name);
        Assert.Equal(2, initial.Tables[0].Columns.Count);
        var users = Assert.Single(result.Schema.Tables);
        Assert.Equal("users", users.Name);
        Assert.Equal(2, users.Columns.Count);
        Assert.Equal("display_name", users.Columns[0].Name);
        Assert.False(users.Columns[0].IsNullable);
        Assert.Equal("created_at", users.Columns[1].Name);
        Assert.Equal("timestamp", users.Columns[1].SqlType);
        Assert.False(users.Columns[1].IsNullable);
        Assert.Equal("now()", users.Columns[1].DefaultExpression);
    }

    [Theory]
    [InlineData("CREATE TABLE things (id integer);", "DDL200")]
    [InlineData("DROP TABLE missing;", "DDL201")]
    [InlineData("ALTER TABLE missing ADD COLUMN id integer;", "DDL202")]
    [InlineData("CREATE TABLE things (id time with time zone);", "DDL205")]
    [InlineData("ALTER TABLE things DROP COLUMN missing;", "DDL204")]
    [InlineData("ALTER TABLE things RENAME COLUMN missing TO other;", "DDL204")]
    public void DiagnosesSchemaInvalidChangesWithSourceSpans(string sql, string expectedCode)
    {
        var schema = sql.Contains("time with time zone", System.StringComparison.Ordinal)
            ? new DatabaseSchema(Array.Empty<Table>())
            : new DatabaseSchema(new[]
            {
                new Table("things", new[] { new Column("id", "integer") }),
            });

        var result = PostgreSqlMigrationAnalyzer.Analyze(schema, sql);

        var diagnostic = Assert.Single(result.Diagnostics, item => item.Code == expectedCode);
        Assert.InRange(diagnostic.Span.Start, 0, sql.Length);
        Assert.InRange(diagnostic.Span.Length, 0, sql.Length - diagnostic.Span.Start);
    }

    [Fact]
    public void SupportsConditionalCreateAndDropAsNoOps()
    {
        var schema = new DatabaseSchema(new[]
        {
            new Table("things", new[] { new Column("id", "integer") }),
        });

        var result = PostgreSqlMigrationAnalyzer.Analyze(schema, @"
            CREATE TABLE IF NOT EXISTS things (changed text);
            DROP TABLE IF EXISTS missing;
            ALTER TABLE things ADD COLUMN IF NOT EXISTS id text;");

        Assert.False(result.HasErrors, string.Join("\n", result.Diagnostics.Select(item => item.ToString())));
        var things = Assert.Single(result.Schema.Tables);
        Assert.Single(things.Columns);
        Assert.Equal("integer", things.Columns[0].SqlType);
    }

    [Fact]
    public void AppliesCompositePrimaryKeysAndDropsExistingTables()
    {
        var result = PostgreSqlMigrationAnalyzer.Analyze(new DatabaseSchema(Array.Empty<Table>()), @"
            CREATE TABLE memberships (
                user_id integer,
                group_id integer,
                PRIMARY KEY (user_id, group_id)
            );
            DROP TABLE memberships;");

        Assert.False(result.HasErrors, string.Join("\n", result.Diagnostics.Select(item => item.ToString())));
        Assert.Empty(result.Schema.Tables);

        var created = PostgreSqlMigrationAnalyzer.Analyze(
            new DatabaseSchema(Array.Empty<Table>()),
            "CREATE TABLE memberships (user_id integer, group_id integer, PRIMARY KEY (user_id, group_id));");
        var table = Assert.Single(created.Schema.Tables);
        Assert.All(table.Columns, column => Assert.True(column.IsPrimaryKey));
        Assert.All(table.Columns, column => Assert.False(column.IsNullable));
    }

