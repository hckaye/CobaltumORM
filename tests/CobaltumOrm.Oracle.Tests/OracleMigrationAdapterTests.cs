    [Fact]
    public async Task OracleAlterDropRenameAndRawCommandsUseOracleSyntax()
    {
        var connection = new RecordingDbConnection { HistoryTableExists = false };
        await new MigrationRunner(new OracleMigrationAdapter()).MigrateUpAsync(
            connection,
            new[] { MigrationInfo.Create<ChangeOracleTablesMigration>(2, "Change Oracle tables") });

        var commands = connection.Executions
            .Where(execution => execution.TransactionId.HasValue)
            .Where(execution => !execution.CommandText.StartsWith("INSERT INTO", StringComparison.Ordinal))
            .Select(execution => execution.CommandText)
            .ToArray();
        Assert.Equal(
            new[]
            {
                "ALTER TABLE \"app\".\"widgets\" ADD (\"nickname\" VARCHAR2(50))",
                "ALTER TABLE \"app\".\"widgets\" MODIFY (\"created_utc\" TIMESTAMP WITH TIME ZONE NOT NULL)",
                "ALTER TABLE \"app\".\"widgets\" MODIFY (\"legacy_code\" NULL)",
                "ALTER TABLE \"app\".\"widgets\" RENAME TO \"accounts\"",
                "ALTER TABLE \"app\".\"accounts\" RENAME COLUMN \"nickname\" TO \"display_name\"",
                "ALTER TABLE \"app\".\"accounts\" DROP COLUMN \"obsolete\"",
                "DROP TABLE \"app\".\"old_widgets\"",
                "UPDATE \"app\".\"accounts\" SET \"display_name\" = 'unknown' WHERE \"display_name\" IS NULL",
            },
            commands);
    }

    [Fact]
    public void HistoryCommandsUseOracleIdentifiersAndColonParameters()
    {
        var adapter = new OracleMigrationAdapter();
        IMigrationDatabaseAdapter boundary = adapter;
        var appliedUtc = new DateTimeOffset(2026, 8, 9, 12, 34, 56, TimeSpan.FromHours(9));

        var ensure = boundary.CreateEnsureHistoryTableCommand("meta", "history\"");
        var read = boundary.CreateReadHistoryCommand("meta", "history\"");
        var insert = boundary.CreateInsertHistoryCommand("meta", "history\"", 42, "Create accounts", appliedUtc);
        var delete = boundary.CreateDeleteHistoryCommand("meta", "history\"", 42);
        var exists = adapter.CreateHistoryTableExistsCommand("meta", "history\"");

        Assert.Contains("EXECUTE IMMEDIATE", ensure.CommandText, StringComparison.Ordinal);
        Assert.Contains("CREATE TABLE \"meta\".\"history\"\"\"", ensure.CommandText, StringComparison.Ordinal);
        Assert.Contains("IF SQLCODE <> -955", ensure.CommandText, StringComparison.Ordinal);
        Assert.DoesNotContain("-942", ensure.CommandText, StringComparison.Ordinal);
        Assert.Equal(
            "SELECT \"version\" FROM \"meta\".\"history\"\"\" ORDER BY \"version\"",
            read.CommandText);
        Assert.Equal(
            "INSERT INTO \"meta\".\"history\"\"\" (\"version\", \"description\", \"applied_utc\") " +
            "VALUES (:version, :description, :applied_utc)",
            insert.CommandText);
        Assert.Equal(42L, insert.Parameters[0].Value);
        Assert.Equal("Create accounts", insert.Parameters[1].Value);
        Assert.Equal(TimeSpan.Zero, Assert.IsType<DateTimeOffset>(insert.Parameters[2].Value).Offset);
        Assert.Equal(
            "DELETE FROM \"meta\".\"history\"\"\" WHERE \"version\" = :version",
            delete.CommandText);
        Assert.Equal(42L, delete.Parameters[0].Value);
        Assert.Contains("ALL_TABLES", exists.CommandText, StringComparison.Ordinal);
        Assert.Contains("SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')", exists.CommandText, StringComparison.Ordinal);
        Assert.Equal("meta", exists.Parameters[0].Value);
        Assert.Equal("history\"", exists.Parameters[1].Value);
    }

    [Fact]
    public void DefaultSchemaIsUnqualifiedAndIdentifierQuotesAreEscaped()
    {
        var adapter = new OracleMigrationAdapter();
