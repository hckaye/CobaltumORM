    [Fact]
    public void BuildSchemaReconstructsGeneratedCreateAlterDropAndRenameCommands()
    {
        var adapter = new OracleMigrationAdapter();
        var schema = adapter.BuildSchema(new[]
        {
            new MigrationCommand(
                "CREATE TABLE \"app\".\"users\" (" +
                "\"id\" NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, " +
                "\"name\" VARCHAR2(50), \"created\" TIMESTAMP WITH TIME ZONE)"),
            new MigrationCommand("ALTER TABLE \"app\".\"users\" ADD (\"active\" NUMBER(1,0) NOT NULL)"),
            new MigrationCommand("ALTER TABLE \"app\".\"users\" MODIFY (\"name\" CLOB NOT NULL)"),
            new MigrationCommand("ALTER TABLE \"app\".\"users\" MODIFY (\"created\" NULL)"),
            new MigrationCommand("ALTER TABLE \"app\".\"users\" RENAME COLUMN \"name\" TO \"display_name\""),
            new MigrationCommand("ALTER TABLE \"app\".\"users\" RENAME TO \"accounts\""),
            new MigrationCommand("UPDATE \"app\".\"accounts\" SET \"display_name\" = 'unknown'"),
            new MigrationCommand("ALTER TABLE \"app\".\"accounts\" DROP COLUMN \"active\""),
        });

        var table = Assert.Single(schema.Tables);
        Assert.Equal("app", table.SchemaName);
        Assert.Equal("accounts", table.Name);
        Assert.Equal(new[] { "id", "display_name", "created" }, table.Columns.Select(column => column.Name));
        Assert.Equal("NUMBER(10,0)", table.Columns[0].SqlType);
        Assert.True(table.Columns[0].IsIdentity);
        Assert.True(table.Columns[0].IsPrimaryKey);
        Assert.False(table.Columns[0].IsNullable);
        Assert.Equal("CLOB", table.Columns[1].SqlType);
        Assert.False(table.Columns[1].IsNullable);
        Assert.True(table.Columns[2].IsNullable);
    }

    [Fact]
    public void BuildSchemaSupportsFlywayOracleHistoryTableAndIgnoresDataStatements()
    {
        var adapter = new OracleMigrationAdapter();
        var schema = adapter.BuildSchema(new[]
        {
            new MigrationCommand(@"
                -- Oracle Flyway history table
                CREATE TABLE ""flyway_schema_history"" (
                    ""installed_rank"" NUMBER(10) NOT NULL,
                    ""version"" VARCHAR2(50),
                    ""description"" VARCHAR2(200) NOT NULL,
                    ""type"" VARCHAR2(20) NOT NULL,
                    ""script"" VARCHAR2(1000) NOT NULL,
                    ""checksum"" NUMBER(10),
                    ""installed_by"" VARCHAR2(100) NOT NULL,
                    ""installed_on"" TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                    ""execution_time"" NUMBER(10) NOT NULL,
                    ""success"" NUMBER(1) NOT NULL,
                    CONSTRAINT ""flyway_schema_history_pk"" PRIMARY KEY (""installed_rank"")
                );
                INSERT INTO ""flyway_schema_history"" (""installed_rank"") VALUES (1);
                UPDATE ""flyway_schema_history"" SET ""success"" = 1;
                DELETE FROM ""flyway_schema_history"" WHERE ""installed_rank"" = 1;
            "),
        });

        var table = Assert.Single(schema.Tables);
        Assert.Null(table.SchemaName);
        Assert.Equal("flyway_schema_history", table.Name);
        Assert.Equal(10, table.Columns.Count);
        Assert.Equal("NUMBER(10)", table.Columns[0].SqlType);
        Assert.True(table.Columns[0].IsPrimaryKey);
        Assert.False(table.Columns[0].IsNullable);
        Assert.Equal("SYSTIMESTAMP", table.Columns[7].DefaultExpression);
    }

    [Theory]
    [InlineData("CREATE VIEW \"users_view\" AS SELECT 1 FROM DUAL")]
    [InlineData("CREATE INDEX \"users_idx\" ON \"users\" (\"id\")")]
    [InlineData("ALTER TABLE \"users\" ADD CONSTRAINT \"fk\" FOREIGN KEY (\"id\") REFERENCES \"other\" (\"id\")")]
    public void BuildSchemaRejectsUnsupportedSchemaChangingStatements(string sql)
    {
        var exception = Assert.Throws<MigrationValidationException>(
            () => new OracleMigrationAdapter().BuildSchema(new[] { new MigrationCommand(sql) }));
        Assert.Contains("Final schema could not be determined", exception.Message, StringComparison.Ordinal);
    }

    [Fact]
    public async Task DryRunBuildsFinalOracleSchemaWithoutApplyingCommands()
    {
        var connection = new RecordingDbConnection { HistoryTableExists = false };
        var dryRun = await new MigrationRunner(new OracleMigrationAdapter()).DryRunUpAsync(
            connection,
            new[] { MigrationInfo.Create<DryRunOracleMigration>(3, "Dry-run Oracle migration") });

        Assert.DoesNotContain(connection.Executions, execution => execution.TransactionId.HasValue);
        var table = Assert.Single(dryRun.FinalSchema.Tables);
        Assert.Equal("preview_users", table.Name);
        Assert.Equal(new[] { "id", "name" }, table.Columns.Select(column => column.Name));
        Assert.Equal("NUMBER(19,0)", table.Columns[0].SqlType);
        Assert.True(table.Columns[0].IsIdentity);
    }

    [Fact]
    public async Task InvalidColumnDeclarationsAreRejectedBeforeExecution()
    {
        await Assert.ThrowsAsync<MigrationValidationException>(() => RunMigration(
            MigrationInfo.Create<MissingTypeMigration>(4, "Missing type")));
        await Assert.ThrowsAsync<MigrationValidationException>(() => RunMigration(
            MigrationInfo.Create<DuplicateColumnMigration>(5, "Duplicate column")));
        await Assert.ThrowsAsync<MigrationValidationException>(() => RunMigration(
            MigrationInfo.Create<InvalidIdentityMigration>(6, "Invalid identity")));
        await Assert.ThrowsAsync<MigrationValidationException>(() => RunMigration(
            MigrationInfo.Create<CompositePrimaryKeyMigration>(7, "Composite primary key")));
    }

    private static async Task RunMigration(MigrationInfo migration)
    {
        await new MigrationRunner(new OracleMigrationAdapter()).MigrateUpAsync(
            new RecordingDbConnection { HistoryTableExists = false },
            new[] { migration });
    }
